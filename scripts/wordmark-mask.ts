import { writeFileSync } from 'node:fs';
import sharp from 'sharp';

/*
 * Task 22: the SURI wordmark (public/suri-wordmark.png, the loader's logo) as a small 8-bit coverage mask, written to
 * src/three/wordmark-mask.ts so the deboss texture is built synchronously at runtime (no font or image load to wait
 * for, the same in stage, snapshots and tiles).
 *   npx tsx scripts/wordmark-mask.ts
 */
const W = 192, H = 32, PAD = 4;
const src = sharp('public/suri-wordmark.png');
const { width = 0, height = 0 } = await src.metadata();
const iw = W - 2 * PAD, ih = Math.round((iw * height) / width);
if (ih > H - 2) throw new Error(`wordmark too tall for ${W}x${H}: ${ih}`);
const alpha = await sharp('public/suri-wordmark.png').extractChannel('alpha').resize(iw, ih, { kernel: 'lanczos3' }).raw().toBuffer();
const out = new Uint8Array(W * H);
const top = Math.floor((H - ih) / 2);
for (let y = 0; y < ih; y++) for (let x = 0; x < iw; x++) out[(top + y) * W + PAD + x] = alpha[y * iw + x];
const b64 = Buffer.from(out).toString('base64');
writeFileSync(
  'src/three/wordmark-mask.ts',
  `// Generated by scripts/wordmark-mask.ts from public/suri-wordmark.png: do not edit.\n` +
    `/** SURI wordmark coverage, ${W}x${H}, one byte per pixel, rows top to bottom, base64. */\n` +
    `export const WORDMARK_MASK = { w: ${W}, h: ${H}, data: '${b64}' };\n`,
);
console.log('wrote src/three/wordmark-mask.ts', W, H, ih, b64.length);
